#!/usr/bin/env bash
#
# Tool ablation — run one manifest once per arm, changing exactly one thing:
# which tools the recovery agent is given.
#
#   no-grep    --disable-tool grep     — no exact text search over the repo
#   no-search  --disable-tool search   — no semantic search over the KB
#   no-read    --disable-tool read_file
#   no-list    --disable-tool list_dir
#
# The control is an existing batch of the same manifest, provider and model,
# run with every tool on the canonical prompt (`secpat recover --manifest-path`).
# It is not rerun. Every arm uses the same provider, model, manifest, KB cache and
# stage-3 derivation as the control, so the only difference between an arm and
# its control is the missing tool. A disabled tool is absent, not stubbed, in both
# places the model learns what it can do:
#
#   --disable-tool <tool>   drops it from the schemas sent to the model
#   --system-prompt-file    runs the arm on prompts/<arm>.md beside this script — a
#                           copy of the canonical prompt with that tool edited out
#
# The canonical prompt (recovery_agent/prompt.py) is never rewritten to run an
# experiment: the control has to be on the prompt it ran on. The copies are
# generated by generate_prompts.py, and this script checks they are current
# before spending a single API call.
#
# Layout, all inside --output-dir:
#
#   <control>/                     the control batch (must exist)
#   ablation-<arm>-<label>/        one batch per arm (<label> = --model, else --provider)
#   ablation-<label>.md / .json    the comparison
#
# A rerun resumes: records that already have a recovery.json in an arm's folder
# are never run again (a pending manifest of the rest is built per arm).
#
# Every arm and the control are scored against --groundtruth-path in the same pass
# (no model calls), so all of them are compared on one ground truth and one
# scoring version; --no-rescore-control reads the control's newest evaluation
# instead. An arm that fails records does not abort the experiment: the remaining
# arms still run, and the summary says which arm failed.
#
# Usage:
#   secpat ablation run --manifest-path <m.json> --groundtruth-path <snapshot> \
#       --output-dir <dir> --control <batch> [--provider P] [--model M]
#   ... --arms no-grep               # one arm (default: no-grep,no-search)
#   ... --no-evaluate                # recovery only, score later
#   ... --evaluate-only              # score + compare what is on disk
#   ... --dry-run
#
# Any other flag is passed straight through to `secpat recover` (--only, --skip,
# --sleep, --parallel, --rebuild-kb, ...). Paths are relative to where you run it.
#
# The arm prompts themselves:
#   secpat ablation prompts          # (re)write them; --check verifies
#
# Run it as `secpat ablation run`, which also points PYTHON at the interpreter
# that has the package installed.

set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PYTHON="${PYTHON:-python3}"

# The header above, as help text.
usage() { awk 'NR>1 && /^#/ {sub(/^# ?/, ""); print; next} NR>1 {exit}' "${BASH_SOURCE[0]}"; }

MANIFEST=""
GROUND_TRUTH=""
OUT_DIR=""
CONTROL=""
PROVIDER="openai"
MODEL=""
ARMS="no-grep,no-search"
EVALUATE=1
RECOVER=1
RESCORE_CONTROL=1
DRY_RUN=0
PASSTHROUGH=()

while [[ $# -gt 0 ]]; do
  case "$1" in
    --manifest-path)      MANIFEST="$2"; shift 2 ;;
    --manifest-path=*)    MANIFEST="${1#*=}"; shift ;;
    --groundtruth-path)   GROUND_TRUTH="$2"; shift 2 ;;
    --groundtruth-path=*) GROUND_TRUTH="${1#*=}"; shift ;;
    --output-dir)         OUT_DIR="$2"; shift 2 ;;
    --output-dir=*)       OUT_DIR="${1#*=}"; shift ;;
    --control)            CONTROL="$2"; shift 2 ;;
    --control=*)          CONTROL="${1#*=}"; shift ;;
    --provider)           PROVIDER="$2"; shift 2 ;;
    --provider=*)         PROVIDER="${1#*=}"; shift ;;
    --model)              MODEL="$2"; shift 2 ;;
    --model=*)            MODEL="${1#*=}"; shift ;;
    --arms)               ARMS="$2"; shift 2 ;;
    --arms=*)             ARMS="${1#*=}"; shift ;;
    --no-evaluate)        EVALUATE=0; shift ;;
    --evaluate-only)      RECOVER=0; shift ;;
    --no-rescore-control) RESCORE_CONTROL=0; shift ;;
    --dry-run)            DRY_RUN=1; PASSTHROUGH+=("--dry-run"); shift ;;
    -h|--help)            usage; exit 0 ;;
    *)                    PASSTHROUGH+=("$1"); shift ;;
  esac
done

LABEL="${MODEL:-$PROVIDER}"

[[ -n "$MANIFEST" ]] || { echo "error: --manifest-path is required" >&2; exit 2; }
[[ -n "$OUT_DIR" ]] || { echo "error: --output-dir is required" >&2; exit 2; }
[[ -n "$CONTROL" ]] || { echo "error: --control is required (the control batch's folder name)" >&2; exit 2; }
if [[ $EVALUATE -eq 1 && -z "$GROUND_TRUTH" ]]; then
  echo "error: --groundtruth-path is required to score (or pass --no-evaluate)" >&2
  exit 2
fi
[[ -f "$MANIFEST" ]] || { echo "error: manifest not found: $MANIFEST" >&2; exit 2; }
[[ -d "$OUT_DIR/$CONTROL" ]] || { echo "error: control batch not found: $OUT_DIR/$CONTROL" >&2; exit 2; }
if [[ $EVALUATE -eq 1 && ! -d "$GROUND_TRUTH" ]]; then
  echo "error: ground-truth snapshot not found: $GROUND_TRUTH" >&2
  exit 2
fi

# arm name -> the flags it runs with: the withheld tool and that arm's own copy
# of the prompt. The two always travel together — withholding the tool while
# running on a prompt that still lists it is the one mistake that silently makes
# an arm measure "told about a tool it cannot call" instead of "without the tool".
arm_flags() {
  case "$1" in
    no-grep)   echo "--disable-tool grep      --system-prompt-file $HERE/prompts/no-grep.md" ;;
    no-search) echo "--disable-tool search    --system-prompt-file $HERE/prompts/no-search.md" ;;
    no-read)   echo "--disable-tool read_file --system-prompt-file $HERE/prompts/no-read.md" ;;
    no-list)   echo "--disable-tool list_dir  --system-prompt-file $HERE/prompts/no-list.md" ;;
    *)         return 1 ;;
  esac
}

batch_name() { echo "ablation-${1}-${LABEL}"; }

IFS=',' read -r -a ARM_LIST <<< "$ARMS"
for arm in "${ARM_LIST[@]}"; do
  if ! arm_flags "$arm" >/dev/null; then
    echo "error: unknown arm '$arm' (no-grep, no-search, no-read, no-list)" >&2
    exit 2
  fi
done

# A stale arm prompt is a wasted experiment, so check before the first API call.
if [[ $RECOVER -eq 1 ]] && ! "$PYTHON" -m secpat_recovery.ablation.generate_prompts --check >/dev/null; then
  echo "error: the arms' prompt copies are out of date with the canonical SYSTEM." >&2
  echo "       regenerate them, review the diff, then re-run:" >&2
  echo "       secpat ablation prompts" >&2
  exit 2
fi

# The manifest's records that have no recovery.json in the batch folder yet.
# Writes the pending manifest to $3 and prints "done N, pending M". Its records'
# paths are written absolute: the pending manifest lives in a temp folder, and a
# record's paths resolve relative to the manifest that lists it.
pending_manifest() {
  "$PYTHON" - "$1" "$2" "$3" <<'EOF'
import json, sys
from pathlib import Path
from secpat_recovery.manifest import load_records
manifest, batch_dir, out = map(Path, sys.argv[1:])
data = json.loads(manifest.read_text(encoding="utf-8"))
runs = load_records(manifest)
pending = [r for r in runs
           if not (batch_dir / f"{r['pattern']}__{r['repo']}" / "recovery.json").is_file()]
out.write_text(json.dumps({**data, "runs": pending}, indent=2) + "\n", encoding="utf-8")
print(f"done {len(runs) - len(pending)}, pending {len(pending)}")
EOF
}

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

MODEL_FLAGS=(--provider "$PROVIDER")
[[ -n "$MODEL" ]] && MODEL_FLAGS+=(--model "$MODEL")

echo "Tool ablation — $PROVIDER${MODEL:+ / $MODEL}"
echo "  manifest : $MANIFEST"
echo "  arms     : ${ARM_LIST[*]}"
echo "  control  : $OUT_DIR/$CONTROL  (not rerun)"
echo "  scoring  : $([[ $EVALUATE -eq 1 ]] && echo "against $GROUND_TRUTH" || echo "skipped")"
echo

declare -a FAILED=()

if [[ $RECOVER -eq 1 ]]; then
  for arm in "${ARM_LIST[@]}"; do
    batch="$(batch_name "$arm")"
    flags=$(arm_flags "$arm")
    pending="$TMP/pending_${arm}.json"

    status="$(pending_manifest "$MANIFEST" "$OUT_DIR/$batch" "$pending")"
    echo "=============================================================="
    echo "ARM: $arm  ->  $OUT_DIR/$batch"
    echo "  flags: $flags"
    echo "  $status"
    echo "=============================================================="
    if [[ "$status" == *"pending 0" ]]; then
      echo "  nothing to run"
      echo
      continue
    fi

    # shellcheck disable=SC2086  # deliberate word-splitting: arm_flags is a flag list
    "$PYTHON" -m secpat_recovery.cli recover \
      --manifest-path "$pending" \
      "${MODEL_FLAGS[@]}" \
      --batch-path "$OUT_DIR/$batch" \
      $flags \
      ${PASSTHROUGH+"${PASSTHROUGH[@]}"}
    rc=$?
    if [[ $rc -ne 0 ]]; then
      echo "  arm '$arm' finished with exit $rc (some records failed)" >&2
      FAILED+=("$arm")
    fi
    echo
  done
fi

if [[ $DRY_RUN -eq 1 ]]; then
  echo "Dry run — nothing was executed."
  exit 0
fi
[[ $EVALUATE -eq 0 ]] && exit $(( ${#FAILED[@]} > 0 ))

to_score=()
[[ $RESCORE_CONTROL -eq 1 ]] && to_score+=("$CONTROL")
for arm in "${ARM_LIST[@]}"; do to_score+=("$(batch_name "$arm")"); done

for batch in "${to_score[@]}"; do
  if [[ ! -d "$OUT_DIR/$batch" ]]; then
    echo "  skipping score of $OUT_DIR/$batch — no such batch" >&2
    continue
  fi
  echo "=============================================================="
  echo "SCORING: $OUT_DIR/$batch"
  echo "=============================================================="
  "$PYTHON" -m secpat_recovery.cli evaluate \
    --batch-path "$OUT_DIR/$batch" \
    --manifest-path "$MANIFEST" \
    --groundtruth-path "$GROUND_TRUTH" || echo "  scoring of $batch reported failures" >&2
  echo
done

echo "=============================================================="
echo "COMPARISON"
echo "=============================================================="
REPORT_ARGS=(--output-root "$OUT_DIR" --control full --tag "$LABEL"
             --out "$OUT_DIR/ablation-${LABEL}.md" --batch "$CONTROL")
for arm in "${ARM_LIST[@]}"; do
  [[ -d "$OUT_DIR/$(batch_name "$arm")" ]] && REPORT_ARGS+=(--batch "$(batch_name "$arm")")
done
"$PYTHON" -m secpat_recovery.ablation.report "${REPORT_ARGS[@]}"
echo

echo "Done. Arm batches:"
for arm in "${ARM_LIST[@]}"; do echo "  $OUT_DIR/$(batch_name "$arm")"; done
if [[ ${#FAILED[@]} -gt 0 ]]; then
  echo "Arms with failed records: ${FAILED[*]}" >&2
  exit 1
fi
